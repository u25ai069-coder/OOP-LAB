public class opperators {
    public static void main(String[] args) {
        int a=20, b=5;

        int sum = a + b;
        int sub = a - b;
        int mul = a * b;
        int div = a / b;
        int mod = a % b;

        System.out.println("Sum: " + sum + " Sub: " + sub + " Mult: " + mul + " Div " + div + " Mod " + mod);
    }
}
